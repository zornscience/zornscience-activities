// Builds test-policy-checker/map.js: one SVG path per state (50 states and DC) and a label point for each.
// The boundaries are the US Census Bureau cartographic boundary files (public domain) as packaged by us-atlas
// (ISC license), already projected to Albers USA in a 975 x 610 box, with Alaska and Hawaii moved below.
// The map rarely changes, so its packages are not dev dependencies. To rebuild, in an empty scratch folder:
//   npm i us-atlas@3.0.1 d3-geo@3.1.1 topojson-client@3.1.0 topojson-simplify@3.0.3
//   node /path/to/repo/test-policy-checker/tools/build-map.mjs
// Run it from that scratch folder (it reads node_modules there) and it writes map.js in the repository.
import fs from "fs";
import path from "path";
import {fileURLToPath} from "url";
import {createRequire} from "module";

const require = createRequire(path.join(process.cwd(), "index.js"));
const {feature} = require("topojson-client");
const {presimplify, simplify} = require("topojson-simplify");
const {geoPath} = require("d3-geo");

const TARGET = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "map.js");
const FIPS = {"01":"AL","02":"AK","04":"AZ","05":"AR","06":"CA","08":"CO","09":"CT","10":"DE","11":"DC","12":"FL","13":"GA","15":"HI","16":"ID","17":"IL","18":"IN","19":"IA","20":"KS","21":"KY","22":"LA","23":"ME","24":"MD","25":"MA","26":"MI","27":"MN","28":"MS","29":"MO","30":"MT","31":"NE","32":"NV","33":"NH","34":"NJ","35":"NM","36":"NY","37":"NC","38":"ND","39":"OH","40":"OK","41":"OR","42":"PA","44":"RI","45":"SC","46":"SD","47":"TN","48":"TX","49":"UT","50":"VT","51":"VA","53":"WA","54":"WV","55":"WI","56":"WY"};
// Label points moved by hand where the centroid falls on a border or in water.
const LABEL = {MI: [693, 196], LA: [566, 470], FL: [790, 512], ID: [196, 160], KY: [694, 322], HI: [305, 566], AK: [110, 520]};
// States too small to label or click on the map; the page lists them as buttons under the map.
const SMALL = ["VT", "NH", "MA", "RI", "CT", "NJ", "DE", "MD", "DC"];

let topo = JSON.parse(fs.readFileSync(require.resolve("us-atlas/states-albers-10m.json"), "utf8"));
topo = simplify(presimplify(topo), 0.5);
const draw = geoPath().digits(1);
const states = {};
for (const f of feature(topo, topo.objects.states).features) {
  const code = FIPS[f.id];
  if (!code) continue;
  states[code] = {d: draw(f), label: LABEL[code] || draw.centroid(f).map(Math.round), small: SMALL.indexOf(code) >= 0};
}
const codes = Object.keys(states).sort();
if (codes.length !== 51) throw new Error("expected 51 states, got " + codes.length);
const lines = codes.map(function (c) { return "    " + JSON.stringify(c) + ": " + JSON.stringify(states[c]); });
fs.writeFileSync(TARGET, [
  "// Generated by tools/build-map.mjs from us-atlas 3.0.1 (US Census Bureau boundaries, Albers USA). Do not edit by hand.",
  "(function () {",
  "  \"use strict\";",
  "  var root = document.querySelector('[data-zsa-activity=\"test-policy-checker\"]');",
  "  if (!root) return;",
  "  var map = {width: 975, height: 610, states: {",
  lines.join(",\n"),
  "  }};",
  "  root.addEventListener(\"zsa:request-map\", function (event) { event.detail.receive(map); }, {once: true});",
  "}());",
  ""
].join("\n"));
console.log("wrote " + TARGET);

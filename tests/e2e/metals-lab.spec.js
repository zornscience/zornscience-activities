'use strict';
var {test, expect} = require('@playwright/test');
var path = require('node:path');
test.use({reducedMotion:'reduce'});
for (var sample of ['A','B','C']) {
  test('Unknown ' + sample + ': investigate, react, observe and dispose', async function ({page}, testInfo) {
    var id = testInfo.title.match(/Unknown ([ABC])/)[1];
    var errors = [];
    page.on('pageerror', function (e) { errors.push(e.message); });
    await page.goto('/metals-lab/');
    await page.locator('[data-sample="'+id+'"]').click();
    await expect(page.locator('#sample-badge')).toHaveText('UNKNOWN '+id);
    await page.locator('[data-station=malleability]').click();
    await page.getByRole('button',{name:'Press with pestle',exact:true}).click();
    await expect(page.locator('#observation')).toContainText(id === 'A' ? 'flattens' : 'fractures');
    await page.locator('[data-station=conductivity]').click();
    await page.getByRole('button',{name:'Touch probes to solid'}).click();
    await expect(page.locator('#meter-value')).toHaveText({A:'STRONG',B:'NONE',C:'WEAK'}[id]);
    await page.getByRole('button',{name:'Lift probes'}).click();
    await expect(page.locator('#meter-value')).toHaveText('OPEN');
    await page.locator('[data-station=acid]').click();
    await expect(page.locator('#add-solid')).toBeDisabled();
    await expect(page.locator('#dispose')).toBeDisabled();
    await page.locator('#add-acid').click();
    await expect(page.locator('#add-solid')).toBeEnabled();
    await expect(page.locator('[data-sample=A]')).toBeDisabled();
    await expect(page.locator('#reset')).toBeDisabled();
    await page.locator('#add-solid').click();
    await expect(page.locator('#pause')).toBeVisible();
    await page.locator('#pause').click();
    var frozen = await page.locator('#clock').textContent();
    await page.waitForTimeout(150);
    await expect(page.locator('#clock')).toHaveText(frozen);
    await page.locator('#pause').click();
    await expect(page.locator('#scene-state')).toHaveText('OBSERVATION COMPLETE',{timeout:25000});
    await expect(page.locator('#clock')).toContainText('05:00 / 05:00');
    await expect(page.locator('#temperature')).toHaveText(id === 'A' ? '24.6 °C' : '22.0 °C');
    await expect(page.locator('#observation')).toContainText(id === 'A' ? 'Persistent gas bubbles' : 'No persistent bubbles');
    await expect(page.locator('#dispose')).toBeEnabled();
    await page.locator('#dispose').click();
    await expect(page.locator('#scene-state')).toHaveText('WASTE COLLECTED');
    await expect(page.locator('[data-sample=A]')).toBeEnabled();
    await expect(page.locator('#tube-solid')).toBeHidden();
    await expect(page.locator('#waste-liquid')).toBeVisible();
    await page.locator('#fresh-tube').click();
    await expect(page.locator('#add-acid')).toBeEnabled();
    await expect(page.locator('#add-solid')).toBeDisabled();
    expect(errors).toEqual([]);
  });
}
test('instructions, sharing, mobile sizing and accessibility', async function ({page}) {
  await page.goto('/metals-lab/');
  await page.getByRole('button',{name:'Instructions',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button',{name:'Instructions',exact:true})).toBeFocused();
  await page.getByRole('button',{name:'Share activity',exact:true}).click();
  await expect(page.getByLabel('Share link',{exact:true})).toHaveValue('https://activities.zornscience.org/metals-lab/');
  await page.keyboard.press('Escape');
  await expect(page.locator('#zsa-th-share-toggle')).toBeFocused();
  // A fresh station must cancel a pending destructive-test animation.
  await page.locator('[data-station=malleability]').click();
  await page.locator('#press').click();
  await page.locator('[data-sample=C]').click();
  await expect(page.locator('#observation')).toContainText('fresh portion of Unknown C');
  await page.waitForTimeout(200);
  await expect(page.locator('#observation')).toContainText('fresh portion of Unknown C');
  await page.locator('#reset').click();
  await page.screenshot({path:test.info().outputPath('metals-desktop.png'),fullPage:true});
  await page.evaluate(require('node:fs').readFileSync(path.join(__dirname,'../../node_modules/axe-core/axe.min.js'),'utf8'));
  var results = await page.evaluate(async function () { return (await axe.run(document.querySelector('main'),{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}})).violations.map(function (v) { return {id:v.id,nodes:v.nodes.map(function (n) { return n.target; })}; }); });
  expect(results).toEqual([]);
  await page.setViewportSize({width:390,height:844});
  await expect(page.locator('#apparatus')).toBeVisible();
  expect(await page.evaluate(function () { return document.documentElement.scrollWidth <= window.innerWidth; })).toBe(true);
  await page.screenshot({path:test.info().outputPath('metals-mobile.png'),fullPage:true});
  expect(await page.locator('textarea,input:not([readonly]):not([type=range])').count()).toBe(0);
});

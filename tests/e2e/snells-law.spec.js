test('protractor drag snaps and accessibility scan has no serious violations',async({page})=>{
 await page.goto('/snells-law-lab/');
 const box=await page.locator('#bench').boundingBox();const xy=(x,y)=>[box.x+x*box.width/960,box.y+y*box.height/620];
 await page.mouse.move(...xy(770,155));await page.mouse.down();await page.mouse.move(...xy(480,300),{steps:10});await page.mouse.up();
 await expect(page.locator('#protractor')).toHaveAttribute('transform','translate(480 300)');
 await page.addScriptTag({url:'/node_modules/axe-core/axe.min.js'});
 const issues=await page.evaluate(async()=> (await axe.run()).violations.filter(v=>['serious','critical'].includes(v.impact)).map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)})));
 expect(issues).toEqual([]);
});
test('investigations scaffold measurement, controlled comparisons and the critical threshold',async({page})=>{
 await page.goto('/snells-law-lab/');
 await page.locator('.investigation summary').click();
 await page.locator('#investigate-measure').click();
 await expect(page.locator('#refraction')).toHaveText('Measure θ₂');
 await expect(page.locator('#scene-desc')).not.toContainText('28.1');
 await expect(page.locator('#protractor')).toHaveAttribute('transform','translate(480 300)');
 await expect(page.locator('#critical')).toBeHidden();
 await page.locator('.equation summary').click();
 await expect(page.locator('#equation-values')).not.toContainText('28.1');
 await page.locator('#show-values').check();
 await expect(page.locator('#refraction')).toHaveText('28.1°');
 await expect(page.locator('#equation-values')).toContainText('0.7071');
 await page.locator('#investigate-materials').click();
 await page.locator('#block').selectOption('diamond');
 await expect(page.locator('#incidence')).toHaveText('45.0°');
 expect(parseFloat(await page.locator('#refraction').textContent())).toBeLessThan(28.1);
 await page.locator('#investigate-tir').click();
 await expect(page.locator('#ray-direction')).toHaveText('Glass → Air');
 await expect(page.locator('#index-key')).toContainText('n₁ = 1.500');
 await expect(page.locator('#critical-reading')).toHaveText('Find θc');
 await page.locator('#show-values').check();
 await page.locator('#below-critical').click();
 await expect(page.locator('#scene-state')).toHaveText('REFRACTION');
 await page.locator('#above-critical').click();
 await expect(page.locator('#scene-state')).toHaveText('TOTAL INTERNAL REFLECTION');
 await expect(page.locator('#equation-values')).toContainText('> 1');
 await page.locator('#laser-power').click();await expect(page.locator('#angle-arcs path')).toHaveCount(0);
 await page.locator('#reset').click();
 await expect(page.locator('#show-values')).toBeChecked();
 await expect(page.locator('#ray-direction')).toHaveText('Air → Glass');
 await page.setViewportSize({width:390,height:844});
 const bench=await page.locator('.bench-card').boundingBox(),settings=await page.locator('#material-settings').boundingBox();
 expect(bench.y).toBeLessThan(settings.y);
 await page.locator('.mobile-settings').click();await expect(page.locator('#material-settings')).toBeFocused();
});


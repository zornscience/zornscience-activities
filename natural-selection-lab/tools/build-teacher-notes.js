// Run from the repository root. Generates every expected adult count from the pure model.
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const m = require("../model.js");
const runs = [
  {investigation: 1, index: 0, generations: 15, settings: {}},
  {investigation: 2, index: 0, generations: 30, settings: {changeAt: 10}},
  ...[[100, 0.5], [100, 0], [10, 0.5], [50, 0.5], [200, 0.5]].map(([size, startDark], index) => ({investigation: 3, index, generations: 20, settings: {size, startDark}}))
];
const prompts = [
  "1A. Describe how the percent of dark beetles changed from generation 0 to generation 15. Use numbers from your table.",
  "1B. Explain why the population changed, using the ideas of variation, inheritance, and survival.",
  "1C. Did any single beetle change color during the run? Explain how a population can change even though individual beetles do not.",
  "2A. Describe what happened to the percent of dark beetles after the ground became light, and how quickly the change happened compared with Investigation 1.",
  "2B. Explain why the same trait helped the beetles in generation 5 but hurt them in generation 25.",
  "2C. Predict what would happen if the ground turned dark again at generation 30. Explain your reasoning.",
  "3A. Compare the run that started with no dark beetles to the run that started with 50 percent dark. Why did the change take longer, and where did the first dark beetles come from?",
  "3B. Compare your three population sizes. Which runs were most alike and which varied the most? Use your graph as evidence.",
  "3C. List the conditions a population needs for natural selection to change it, and point to evidence from this lab for each."
];
const lines = ["# Natural Selection Lab teacher notes", "", "Version: 1.0.0", "",
  "Generated by `node natural-selection-lab/tools/build-teacher-notes.js`. All numeric",
  "results below are computed from model.js. Do not edit expected results by hand.", "",
  "## Assignment and interpretation", "",
  "Use ?seed=1 through ?seed=6 for reproducible keys. Keep the guided run order",
  "shown below. Investigation numbers start at 1, indices start at 0. Visiting",
  "another investigation does not consume its stream. An extra Investigation 3",
  "run changes subsequent indices. Predictions do not affect outcomes. Each table",
  "reports adults at generation start; Percent dark is rounded to a whole percent.", "",
  "This is an illustrative teaching model, not real field data. Ask students to",
  "explain variation, inheritance and differential survival and reproduction.",
  "Individuals do not recolor. The composition of offspring changes. Rare random",
  "changes can introduce variation without responding to need. A no-variation",
  "start can acquire dark offspring early or late by chance. Small populations",
  "may lose a color or become extinct. Avoid claiming every individual run must",
  "match an ensemble trend, or that a helpful trait is guaranteed to increase.", "",
  "The drought begins at generation 10. Generation 10 adults face light ground",
  "when they reproduce into generation 11. The same dark trait helps on dark",
  "ground and hurts on light ground. Returning to dark would favor dark survivors",
  "again if that variation exists. Future generations are never shown in the lab.", "",
  "A single small-population run at each size illustrates chance but does not",
  "establish a distribution. Compare results across classmates or use the sixth",
  "run for a repeat. The model tests compare spread across many fixed seeds.", "",
  "## Stable worksheet prompts", "", ...prompts.flatMap(p => [p, ""]),
  "## Computed guided runs", "",
  "All runs use medium selection and rare random color changes. Investigation 3",
  "guided indices: 0 = N100/50%, 1 = N100/0%, 2 = N10/50%, 3 = N50/50%,",
  "4 = N200/50%. Run labels displayed to students are indices plus one.", ""];
for (let seed = 1; seed <= 6; seed++) {
  lines.push("### Seed " + seed, "");
  for (const entry of runs) {
    const run = m.runTo(m.createRun(entry.settings, seed, entry.investigation, entry.index), entry.generations);
    lines.push("Investigation " + entry.investigation + ", run index " + entry.index + ", N = " + run.settings.size + ", start " + 100 * run.settings.startDark + "% dark.", "",
      "| Generation | Dark beetles | Light beetles | Percent dark |", "| --- | --- | --- | --- |");
    for (const r of run.history) lines.push("| " + [r.generation, r.dark, r.light, r.percentDark].join(" | ") + " |");
    if (run.extinct) lines.push("", "No beetles survived, so there is no next generation.");
    lines.push("");
  }
}
const output = lines.join("\n");
const file = path.join(__dirname, "../TEACHER_NOTES.md");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(file, "utf8") !== output) throw new Error("Teacher notes are stale");
  console.log("Teacher notes match all 42 computed guided runs.");
} else {
  fs.writeFileSync(file, output);
  console.log("Generated 42 guided run tables for seeds 1 to 6.");
}
